CREATE TABLE IF NOT EXISTS courses (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- Stable public identifier generated by the application.
    public_id CHAR(36) NOT NULL,

    -- Course identity.
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL,
    code VARCHAR(50) NULL,

    -- Catalogue classification.
    category VARCHAR(100) NOT NULL,
    qualification_level VARCHAR(100) NULL,

    -- Course information.
    description TEXT NULL,
    duration_months INT UNSIGNED NULL,
    eligibility TEXT NULL,
    entrance_exam VARCHAR(200) NULL,

    -- Publication and lifecycle.
    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    -- Optional user who created the course.
    created_by BIGINT UNSIGNED NULL,

    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
        ON UPDATE CURRENT_TIMESTAMP(3),

    PRIMARY KEY (id),

    -- Unique identifiers.
    UNIQUE KEY uq_courses_public_id (public_id),
    UNIQUE KEY uq_courses_slug (slug),

    -- Search and filtering indexes.
    KEY idx_courses_category (category),
    KEY idx_courses_active (is_active),
    KEY idx_courses_name (name),
    KEY idx_courses_created_by (created_by),
    KEY idx_courses_category_active (category, is_active),

    -- Required catalogue values must not be blank.
    CONSTRAINT chk_courses_name_not_blank
        CHECK (CHAR_LENGTH(TRIM(name)) > 0),

    CONSTRAINT chk_courses_slug_format
        CHECK (
            REGEXP_LIKE(slug, '^[a-z0-9]+(-[a-z0-9]+)*$', 'c')
        ),

    CONSTRAINT chk_courses_category_not_blank
        CHECK (CHAR_LENGTH(TRIM(category)) > 0),

    CONSTRAINT chk_courses_code_not_blank
        CHECK (
            code IS NULL
            OR CHAR_LENGTH(TRIM(code)) > 0
        ),

    CONSTRAINT chk_courses_qualification_not_blank
        CHECK (
            qualification_level IS NULL
            OR CHAR_LENGTH(TRIM(qualification_level)) > 0
        ),

    CONSTRAINT chk_courses_entrance_exam_not_blank
        CHECK (
            entrance_exam IS NULL
            OR CHAR_LENGTH(TRIM(entrance_exam)) > 0
        ),

    -- A defined duration must be greater than zero.
    CONSTRAINT chk_courses_duration
        CHECK (
            duration_months IS NULL
            OR duration_months > 0
        ),

    -- Preserve referential integrity if the creator account is removed.
    CONSTRAINT fk_courses_created_by
        FOREIGN KEY (created_by)
        REFERENCES users (id)
        ON DELETE SET NULL

) ENGINE=InnoDB
  DEFAULT CHARSET=utf8mb4
  COLLATE=utf8mb4_0900_ai_ci;
