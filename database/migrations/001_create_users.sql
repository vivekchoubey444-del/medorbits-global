CREATE TABLE IF NOT EXISTS users (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,

    -- Public identifier generated by the application.
    public_id CHAR(36) NOT NULL,

    -- Account identity and authentication.
    name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,

    -- Legacy role field retained for compatibility.
    -- Normalized user_roles should be authoritative when RBAC is enabled.
    role VARCHAR(30) NOT NULL DEFAULT 'user',

    -- Account lifecycle.
    status VARCHAR(30) NOT NULL DEFAULT 'pending',

    -- Email verification.
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    email_verified_at DATETIME(3) NULL,

    -- Phone verification.
    phone VARCHAR(30) NULL,
    phone_verified BOOLEAN NOT NULL DEFAULT FALSE,
    phone_verified_at DATETIME(3) NULL,

    -- Authentication activity.
    last_login_at DATETIME(3) NULL,
    password_changed_at DATETIME(3) NULL,

    -- Lifecycle timestamps.
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
        ON UPDATE CURRENT_TIMESTAMP(3),
    deleted_at DATETIME(3) NULL,

    -- Primary and unique identifiers.
    PRIMARY KEY (id),

    CONSTRAINT uq_users_public_id
        UNIQUE (public_id),

    CONSTRAINT uq_users_email
        UNIQUE (email),

    -- Role validation.
    CONSTRAINT chk_users_role
        CHECK (
            role IN ('user', 'admin', 'counsellor', 'employer')
        ),

    -- Include deleted because the soft-delete consistency constraint
    -- below explicitly supports status = 'deleted'.
    CONSTRAINT chk_users_status
        CHECK (
            status IN (
                'active',
                'pending',
                'suspended',
                'disabled',
                'deleted'
            )
        ),

    -- Prevent empty or whitespace-only identity fields.
    CONSTRAINT chk_users_name_not_blank
        CHECK (CHAR_LENGTH(TRIM(name)) > 0),

    CONSTRAINT chk_users_email_not_blank
        CHECK (CHAR_LENGTH(TRIM(email)) > 0),

    CONSTRAINT chk_users_password_hash_not_blank
        CHECK (CHAR_LENGTH(TRIM(password_hash)) > 0),

    -- Verification timestamps must agree with Boolean flags.
    CONSTRAINT chk_users_email_verified_consistency
        CHECK (
            (email_verified = FALSE AND email_verified_at IS NULL)
            OR
            (email_verified = TRUE AND email_verified_at IS NOT NULL)
        ),

    CONSTRAINT chk_users_phone_verified_consistency
        CHECK (
            (phone_verified = FALSE AND phone_verified_at IS NULL)
            OR
            (phone_verified = TRUE AND phone_verified_at IS NOT NULL)
        ),

    -- A verified phone must have a non-empty phone number.
    CONSTRAINT chk_users_phone_required_when_verified
        CHECK (
            phone_verified = FALSE
            OR (
                phone IS NOT NULL
                AND CHAR_LENGTH(TRIM(phone)) > 0
            )
        ),

    -- Soft-delete consistency.
    CONSTRAINT chk_users_deleted_consistency
        CHECK (
            (status = 'deleted' AND deleted_at IS NOT NULL)
            OR
            (status <> 'deleted' AND deleted_at IS NULL)
        ),

    -- Query indexes.
    KEY idx_users_role (role),
    KEY idx_users_status_created (status, created_at),
    KEY idx_users_last_login (last_login_at),
    KEY idx_users_deleted_at (deleted_at),
    KEY idx_users_phone (phone)

) ENGINE=InnoDB
  DEFAULT CHARSET=utf8mb4
  COLLATE=utf8mb4_0900_ai_ci;
