
'use strict';

/**
 * MedOrbits -- Database Transaction Integration Tests
 *
 * File: tests/database/transactions.test.js
 * Requires: Node.js >= 20, mysql2
 *
 * Required environment:
 *   NODE_ENV=test
 *   TEST_DATABASE_URL=mysql://USER:PASSWORD@HOST:3306/medorbits_test
 *
 * Required table:
 *   test_transaction_records
 *
 * Expected columns:
 *   id    VARCHAR(191) PRIMARY KEY
 *   value VARCHAR(255) NOT NULL
 *
 * Run:
 *   node --test tests/database/transactions.test.js
 *
 * Safety:
 * - Uses the shared test database connection.
 * - Does not create, drop, truncate, or migrate tables.
 * - Uses parameterized SQL values.
 * - Uses unique IDs to isolate test records.
 * - Removes only records created by this suite.
 */

const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const {
  before,
  after,
  test,
} = require('node:test');

const {
  connectTestDatabase,
  getTestDatabaseConnection,
  closeTestDatabase,
} = require('./setup');

const TABLE_NAME = 'test_transaction_records';

let connection;
let tableReady = false;

const insertedIds = new Set();

function uniqueId(prefix) {
  return `${prefix}-${randomUUID()}`;
}

function quoteIdentifier(identifier) {
  if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(identifier)) {
    throw new Error(`Unsafe SQL identifier: ${identifier}`);
  }

  return `\`${identifier}\``;
}

const TABLE = quoteIdentifier(TABLE_NAME);

/**
 * Roll back an active transaction if one exists.
 *
 * This helper intentionally suppresses rollback errors so that
 * the original operation error remains the primary failure.
 */
async function rollbackSafely() {
  if (!connection) {
    return;
  }

  try {
    await connection.rollback();
  } catch {
    // Preserve the original test failure.
  }
}

/**
 * Delete only records whose IDs were generated by this test suite.
 *
 * This is record-level cleanup, not table truncation.
 */
async function cleanupInsertedRecords() {
  if (!connection || insertedIds.size === 0) {
    return;
  }

  const ids = [...insertedIds];
  const placeholders = ids.map(() => '?').join(', ');

  await connection.execute(
    `DELETE FROM ${TABLE} WHERE id IN (${placeholders})`,
    ids,
  );

  insertedIds.clear();
}

async function insertRecord(id, value) {
  await connection.execute(
    `INSERT INTO ${TABLE} (id, value) VALUES (?, ?)`,
    [id, value],
  );

  insertedIds.add(id);
}

async function findRecord(id) {
  const [rows] = await connection.execute(
    `SELECT id, value FROM ${TABLE} WHERE id = ?`,
    [id],
  );

  return rows;
}

before(async () => {
  await connectTestDatabase();

  connection = getTestDatabaseConnection();

  assert.ok(
    connection,
    'The shared test database connection must be available.',
  );

  const [tables] = await connection.execute(
    'SHOW TABLES LIKE ?',
    [TABLE_NAME],
  );

  assert.ok(
    tables.length > 0,
    `Required table "${TABLE_NAME}" is missing. ` +
      'Create it in the dedicated test database setup.',
  );

  // Confirm the required columns exist before running tests.
  const [columns] = await connection.execute(
    `SHOW COLUMNS FROM ${TABLE}`,
  );

  const columnNames = new Set(
    columns.map((column) => column.Field),
  );

  assert.ok(
    columnNames.has('id'),
    `Required column "id" is missing from "${TABLE_NAME}".`,
  );

  assert.ok(
    columnNames.has('value'),
    `Required column "value" is missing from "${TABLE_NAME}".`,
  );

  tableReady = true;
});

after(async () => {
  let cleanupError;

  try {
    await rollbackSafely();
    await cleanupInsertedRecords();
  } catch (error) {
    cleanupError = error;
  }

  // The setup module owns the connection lifecycle.
  try {
    await closeTestDatabase();
  } catch (closeError) {
    if (cleanupError) {
      throw new AggregateError(
        [cleanupError, closeError],
        'Transaction-test cleanup and connection shutdown both failed.',
      );
    }

    throw closeError;
  } finally {
    connection = undefined;
    tableReady = false;
  }

  if (cleanupError) {
    throw cleanupError;
  }
});

test('commits successful operations', async () => {
  assert.ok(tableReady, 'Transaction test table is not ready.');

  const id = uniqueId('commit');

  try {
    await connection.beginTransaction();

    await insertRecord(id, 'committed');

    await connection.commit();
  } catch (error) {
    await rollbackSafely();
    throw error;
  }

  const rows = await findRecord(id);

  assert.equal(rows.length, 1);
  assert.equal(rows[0].id, id);
  assert.equal(rows[0].value, 'committed');
});

test('rolls back writes when a transaction fails', async () => {
  assert.ok(tableReady, 'Transaction test table is not ready.');

  const id = uniqueId('rollback');
  const expectedError = new Error('Simulated transaction failure');

  let actualError;

  try {
    await connection.beginTransaction();

    await insertRecord(id, 'must-not-persist');

    throw expectedError;
  } catch (error) {
    actualError = error;
    await rollbackSafely();
  }

  assert.equal(
    actualError,
    expectedError,
    'The simulated transaction error should be preserved.',
  );

  // The insert was rolled back, so this ID must not be tracked
  // for deletion as a committed record.
  insertedIds.delete(id);

  const rows = await findRecord(id);

  assert.equal(
    rows.length,
    0,
    'A rolled-back transaction must not leave its inserted record behind.',
  );
});

test('preserves a committed write when a separate transaction rolls back', async () => {
  assert.ok(tableReady, 'Transaction test table is not ready.');

  const committedId = uniqueId('committed-a');
  const rolledBackId = uniqueId('rolled-back-b');

  try {
    await connection.beginTransaction();

    await insertRecord(committedId, 'keep');

    await connection.commit();

    await connection.beginTransaction();

    await insertRecord(rolledBackId, 'discard');

    await connection.rollback();

    insertedIds.delete(rolledBackId);
  } catch (error) {
    await rollbackSafely();
    throw error;
  }

  const committedRows = await findRecord(committedId);
  const rolledBackRows = await findRecord(rolledBackId);

  assert.equal(committedRows.length, 1);
  assert.equal(committedRows[0].value, 'keep');

  assert.equal(
    rolledBackRows.length,
    0,
    'The second transaction should not persist its rolled-back insert.',
  );
});

test('rolls back changes to an existing record', async () => {
  assert.ok(tableReady, 'Transaction test table is not ready.');

  const id = uniqueId('update-rollback');

  await insertRecord(id, 'original');

  try {
    await connection.beginTransaction();

    await connection.execute(
      `UPDATE ${TABLE} SET value = ? WHERE id = ?`,
      ['modified', id],
    );

    await connection.rollback();
  } catch (error) {
    await rollbackSafely();
    throw error;
  }

  const rows = await findRecord(id);

  assert.equal(rows.length, 1);
  assert.equal(
    rows[0].value,
    'original',
    'A rolled-back update must restore the original value.',
  );
});

test('commits updates successfully', async () => {
  assert.ok(tableReady, 'Transaction test table is not ready.');

  const id = uniqueId('update-commit');

  await insertRecord(id, 'before');

  try {
    await connection.beginTransaction();

    await connection.execute(
      `UPDATE ${TABLE} SET value = ? WHERE id = ?`,
      ['after', id],
    );

    await connection.commit();
  } catch (error) {
    await rollbackSafely();
    throw error;
  }

  const rows = await findRecord(id);

  assert.equal(rows.length, 1);
  assert.equal(rows[0].value, 'after');
});
